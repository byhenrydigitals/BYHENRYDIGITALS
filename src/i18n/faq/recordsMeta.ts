export function composeFaqEntries(
  language: ActiveLanguageCode,
  localizedRecords: Record<string, FaqLocalizedRecord>
): FaqEntry[] {
  const seenIds = new Set<string>();
  const composed: FaqEntry[] = [];

  for (const meta of FAQ_RECORDS_META) {
    if (seenIds.has(meta.id)) continue;
    seenIds.add(meta.id);

    const localized = localizedRecords[meta.id];
    if (!localized) continue;

    composed.push({
      ...meta,
      language,
      question: localized.question,
      answer: localized.answer,
      keywords: Array.from(
        new Set([...meta.canonicalKeywords, ...(localized.extraKeywords ?? [])])
      ),
      actionLabel: localized.actionLabel,
    });
  }

  return composed;
}
